import { describe, expect, it } from 'vitest'
import {
  BEHAVIOR_ACTOR_INPUT_EXTENSION,
  BEHAVIOR_EVENT_PAYLOAD_EXTENSION,
  BEHAVIOR_MACHINE_CONTEXT_EXTENSION,
  BEHAVIOR_REF_EXTENSION,
} from './behavior.js'

/**
 * Standard Schema v1 specification interface (@standard-schema/spec).
 * Used natively by XState v6 setup({ schemas }).
 */
export interface StandardSchemaV1<Input = unknown, Output = Input> {
  readonly '~standard': {
    readonly version: 1
    readonly vendor: string
    readonly validate: (
      value: unknown,
    ) => StandardSchemaV1.Result<Output> | Promise<StandardSchemaV1.Result<Output>>
    readonly types?: {
      readonly input: Input
      readonly output: Output
    }
  }
}

export namespace StandardSchemaV1 {
  export type Result<Output> = SuccessResult<Output> | FailureResult
  export interface SuccessResult<Output> {
    readonly value: Output
    readonly issues?: undefined
  }
  export interface FailureResult {
    readonly issues: ReadonlyArray<Issue>
  }
  export interface Issue {
    readonly message: string
    readonly path?: ReadonlyArray<PropertyKey>
  }
}

/**
 * Simulated PlayerActorInput contract corresponding to:
 * \@behaviorRef("scene-player.v1")
 * \@actorInput
 * model PlayerActorInput { sceneId: string; autoplay?: boolean = false; initialTime?: float64 = 0; }
 */
export interface PlayerActorInput {
  sceneId: string
  autoplay?: boolean
  initialTime?: number
}

/**
 * AOT compiled validator function for PlayerActorInput.
 * Generated by ttsc (Typia AST transform pass) without runtime validator dependencies.
 */
function validatePlayerActorInput(input: unknown): StandardSchemaV1.Result<PlayerActorInput> {
  const issues: StandardSchemaV1.Issue[] = []
  if (typeof input !== 'object' || input === null) {
    return { issues: [{ message: 'Expected object', path: [] }] }
  }
  const obj = input as Record<string, unknown>
  if (typeof obj.sceneId !== 'string' || obj.sceneId.length === 0) {
    issues.push({ message: 'sceneId must be a non-empty string', path: ['sceneId'] })
  }
  if (obj.autoplay !== undefined && typeof obj.autoplay !== 'boolean') {
    issues.push({ message: 'autoplay must be a boolean', path: ['autoplay'] })
  }
  if (
    obj.initialTime !== undefined &&
    (typeof obj.initialTime !== 'number' || Number.isNaN(obj.initialTime) || obj.initialTime < 0)
  ) {
    issues.push({ message: 'initialTime must be a non-negative number', path: ['initialTime'] })
  }

  return issues.length > 0 ? { issues } : { value: obj as unknown as PlayerActorInput }
}

export const playerActorInputSchema: StandardSchemaV1<unknown, PlayerActorInput> = {
  '~standard': {
    version: 1,
    vendor: 'ttsc-aot',
    validate: validatePlayerActorInput,
  },
}

/**
 * Simulated Discriminated Union Event contract corresponding to:
 * \@eventPayload("PLAY") model PlayEvent { type: "PLAY"; speed?: float64; }
 * \@eventPayload("PAUSE") model PauseEvent { type: "PAUSE"; }
 * \@eventPayload("SEEK") model SeekEvent { type: "SEEK"; time: float64; }
 */
export type PlayerEvent =
  | { type: 'PLAY'; speed?: number }
  | { type: 'PAUSE' }
  | { type: 'SEEK'; time: number }

/**
 * AOT compiled validator function for PlayerEvent discriminated union.
 * Implements O(1) branch elimination using switch statement on discriminator property.
 */
function validatePlayerEvent(input: unknown): StandardSchemaV1.Result<PlayerEvent> {
  if (typeof input !== 'object' || input === null) {
    return { issues: [{ message: 'Event payload must be an object', path: [] }] }
  }
  const event = input as { type?: unknown; [key: string]: unknown }
  if (typeof event.type !== 'string') {
    return { issues: [{ message: 'Event must have a string type discriminator', path: ['type'] }] }
  }

  // O(1) Discriminated union branch elimination
  switch (event.type) {
    case 'PLAY': {
      if (
        event.speed !== undefined &&
        (typeof event.speed !== 'number' || Number.isNaN(event.speed) || event.speed <= 0)
      ) {
        return { issues: [{ message: 'Playback speed must be a positive number', path: ['speed'] }] }
      }
      const value: PlayerEvent = event.speed !== undefined
        ? { type: 'PLAY', speed: event.speed as number }
        : { type: 'PLAY' }
      return { value }
    }
    case 'PAUSE': {
      return { value: { type: 'PAUSE' } }
    }
    case 'SEEK': {
      if (
        typeof event.time !== 'number' ||
        Number.isNaN(event.time) ||
        event.time < 0
      ) {
        return { issues: [{ message: 'Seek time must be a non-negative number', path: ['time'] }] }
      }
      return { value: { type: 'SEEK', time: event.time as number } }
    }
    default:
      return {
        issues: [
          { message: `Unknown event type discriminator "${String(event.type)}"`, path: ['type'] },
        ],
      }
  }
}

export const playerEventSchema: StandardSchemaV1<unknown, PlayerEvent> = {
  '~standard': {
    version: 1,
    vendor: 'ttsc-aot',
    validate: validatePlayerEvent,
  },
}

describe('XState v6 AOT Standard Schema v1 integration', () => {
  it('exposes the standard behavior extension keys', () => {
    expect(BEHAVIOR_ACTOR_INPUT_EXTENSION).toBe('x-oa-sdk-behavior-actor-input')
    expect(BEHAVIOR_MACHINE_CONTEXT_EXTENSION).toBe('x-oa-sdk-behavior-machine-context')
    expect(BEHAVIOR_EVENT_PAYLOAD_EXTENSION).toBe('x-oa-sdk-behavior-event-payload')
    expect(BEHAVIOR_REF_EXTENSION).toBe('x-oa-sdk-behavior-ref')
  })

  it('validates ActorInput conforming to Standard Schema v1 (~standard)', () => {
    // Valid input
    const validResult = playerActorInputSchema['~standard'].validate({
      sceneId: 'sc_scene_001',
      autoplay: true,
      initialTime: 12.5,
    })
    expect(validResult).not.toHaveProperty('issues')
    expect(validResult).toHaveProperty('value')
    if (!('issues' in validResult) || !validResult.issues) {
      const success = validResult as StandardSchemaV1.SuccessResult<PlayerActorInput>
      expect(success.value.sceneId).toBe('sc_scene_001')
      expect(success.value.autoplay).toBe(true)
      expect(success.value.initialTime).toBe(12.5)
    }

    // Invalid input: missing sceneId and wrong type for autoplay
    const invalidResult = playerActorInputSchema['~standard'].validate({
      autoplay: 'yes',
      initialTime: -5,
    })
    expect(invalidResult).toHaveProperty('issues')
    if ('issues' in invalidResult && invalidResult.issues) {
      expect(invalidResult.issues.length).toBe(3)
      expect(invalidResult.issues.map(i => i.path?.[0])).toEqual(['sceneId', 'autoplay', 'initialTime'])
    }
  })

  it('validates Discriminated Union Event payloads with O(1) branch dispatch', () => {
    // Valid PLAY event
    const playResult = playerEventSchema['~standard'].validate({ type: 'PLAY', speed: 1.5 })
    expect(playResult).toHaveProperty('value', { type: 'PLAY', speed: 1.5 })

    // Valid PAUSE event
    const pauseResult = playerEventSchema['~standard'].validate({ type: 'PAUSE' })
    expect(pauseResult).toHaveProperty('value', { type: 'PAUSE' })

    // Valid SEEK event
    const seekResult = playerEventSchema['~standard'].validate({ type: 'SEEK', time: 42 })
    expect(seekResult).toHaveProperty('value', { type: 'SEEK', time: 42 })

    // Invalid SEEK event: negative time
    const invalidSeek = playerEventSchema['~standard'].validate({ type: 'SEEK', time: -1 })
    expect(invalidSeek).toHaveProperty('issues')
    if ('issues' in invalidSeek && invalidSeek.issues) {
      expect(invalidSeek.issues[0]?.message).toContain('non-negative number')
    }

    // Invalid discriminator
    const unknownEvent = playerEventSchema['~standard'].validate({ type: 'FAST_FORWARD' })
    expect(unknownEvent).toHaveProperty('issues')
    if ('issues' in unknownEvent && unknownEvent.issues) {
      expect(unknownEvent.issues[0]?.message).toContain('Unknown event type discriminator')
    }
  })


  it('executes in an XState v6 actor simulator and blocks invalid transitions', () => {
    // Simulated XState v6 actor engine using Standard Schema v1
    class SimulatedXStateActor {
      private state: 'idle' | 'playing' = 'idle'
      private context: { sceneId: string; time: number; playing: boolean }

      constructor(input: unknown) {
        const validated = playerActorInputSchema['~standard'].validate(input)
        if ('issues' in validated && validated.issues && validated.issues.length > 0) {
          throw new Error(`[Actor Initialization Error] ${validated.issues[0]?.message}`)
        }
        const data = (validated as StandardSchemaV1.SuccessResult<PlayerActorInput>).value
        this.context = {
          sceneId: data.sceneId,
          time: data.initialTime ?? 0,
          playing: data.autoplay ?? false,
        }
        if (this.context.playing) this.state = 'playing'
      }

      get snapshot() {
        return { state: this.state, context: { ...this.context } }
      }

      send(rawEvent: unknown) {
        const validated = playerEventSchema['~standard'].validate(rawEvent)
        if ('issues' in validated && validated.issues && validated.issues.length > 0) {
          throw new Error(`[Event Rejected] ${validated.issues[0]?.message}`)
        }
        const event = (validated as StandardSchemaV1.SuccessResult<PlayerEvent>).value

        switch (event.type) {
          case 'PLAY':
            this.state = 'playing'
            this.context.playing = true
            break
          case 'PAUSE':
            this.state = 'idle'
            this.context.playing = false
            break
          case 'SEEK':
            this.context.time = event.time
            break
        }
      }
    }

    // 1. Successful initialization
    const actor = new SimulatedXStateActor({ sceneId: 'intro-video', autoplay: false })
    expect(actor.snapshot.state).toBe('idle')
    expect(actor.snapshot.context.time).toBe(0)

    // 2. State transition via validated event
    actor.send({ type: 'PLAY', speed: 1.0 })
    expect(actor.snapshot.state).toBe('playing')
    expect(actor.snapshot.context.playing).toBe(true)

    // 3. Context update via validated SEEK event
    actor.send({ type: 'SEEK', time: 55 })
    expect(actor.snapshot.context.time).toBe(55)

    // 4. Rejection of invalid actor input
    expect(() => new SimulatedXStateActor({ sceneId: '' })).toThrow(/Actor Initialization Error/)

    // 5. Rejection of invalid event without corrupting actor state
    expect(() => actor.send({ type: 'SEEK', time: -10 })).toThrow(/Event Rejected/)
    // State remains unchanged
    expect(actor.snapshot.context.time).toBe(55)
  })
})
