/**
 * S6 — emit. Wraps rendered source into plugin VFS files and a build report.
 */
import { createHash } from 'node:crypto'
import type { TspGeneratedFile } from '../plugin/types.js'
import type { PyModuleIR, PydanticDiagnosticSeverity } from './ir.js'
import {
  PYDANTIC_FIXED_SETTINGS,
  type PydanticPreset,
  type PydanticSemanticOptions,
  type ResolvedPydanticBuildOptions,
} from './options.js'
import { pickPydanticSemanticOptions } from './semantic-options.js'

export const PYDANTIC_BUILD_REPORT_SCHEMA = 'oa-sdk.pydantic-build-report.v1' as const
export const PYDANTIC_PLUGIN_NAME = 'pydantic' as const
/** S6 output options consumed by file/report emission. */
export const PYDANTIC_S6_READS = ['layout', 'emitOperations'] as const

export const PYDANTIC_GENERATED_BANNER = [
  '# @generated by @oa-sdk/codegen. DO NOT EDIT.',
  `# Requires pydantic>=${PYDANTIC_FIXED_SETTINGS.pydanticFloor}, Python>=${PYDANTIC_FIXED_SETTINGS.pythonFloor}.`,
].join('\n')

export interface PydanticBuildReport {
  schema: typeof PYDANTIC_BUILD_REPORT_SCHEMA
  preset: PydanticPreset
  options: PydanticSemanticOptions
  fixed: typeof PYDANTIC_FIXED_SETTINGS
  output: string
  layout: 'single' | 'split'
  emitOperations: boolean
  /** SHA-256 of the module content without the banner. */
  contentSha256: string
  declarations: { models: number; enums: number; aliases: number; operations: number }
  files: string[]
  diagnostics: Record<PydanticDiagnosticSeverity, number>
}

export interface PydanticEmitResult {
  files: TspGeneratedFile[]
  report: PydanticBuildReport
}

export interface PydanticRenderedSources {
  operations?: string
  packageInit?: string
}

export function emitPydanticFiles(
  source: string,
  ir: PyModuleIR,
  options: ResolvedPydanticBuildOptions,
  rendered: PydanticRenderedSources = {},
): PydanticEmitResult {
  const semantic: PydanticSemanticOptions = pickPydanticSemanticOptions(options)
  const diagnostics: Record<PydanticDiagnosticSeverity, number> = { info: 0, warning: 0, error: 0 }
  for (const d of ir.diagnostics) diagnostics[d.severity] += 1

  const operationDecls = ir.decls.filter(d => d.kind === 'operation')
  const operationPath = `${options.output.split('/').slice(0, -1).join('/')}${options.output.includes('/') ? '/' : ''}operations.py`
  const initPath = `${options.output.split('/').slice(0, -1).join('/')}${options.output.includes('/') ? '/' : ''}__init__.py`
  const extraFiles = options.layout === 'split' && options.emitOperations && operationDecls.length > 0 && rendered.operations !== undefined
    ? [{
      path: operationPath,
      content: rendered.operations,
      sourcePlugin: PYDANTIC_PLUGIN_NAME,
      banner: PYDANTIC_GENERATED_BANNER,
      kind: 'operations',
      exports: ['OperationSpec', 'OPERATIONS',
        ...ir.decls.filter(d => d.kind === 'model' && d.operationOwner !== undefined && d.pyName !== null).map(d => d.pyName as string),
        ...operationDecls.flatMap(d => d.kind === 'operation' ? Object.values(d.modelNames).filter((name): name is string => name !== null && name !== '') : [])],
    }, {
      path: initPath,
      content: rendered.packageInit ?? '"""Generated package marker for Pydantic models and operations."""\n',
      sourcePlugin: PYDANTIC_PLUGIN_NAME,
      banner: PYDANTIC_GENERATED_BANNER,
      kind: 'package',
    }] satisfies TspGeneratedFile[]
    : []
  const report: PydanticBuildReport = {
    schema: PYDANTIC_BUILD_REPORT_SCHEMA,
    preset: options.preset,
    options: semantic,
    fixed: PYDANTIC_FIXED_SETTINGS,
    output: options.output,
    layout: options.layout,
    emitOperations: options.emitOperations,
    contentSha256: createHash('sha256').update(source).digest('hex'),
    declarations: {
      models: ir.decls.filter(d => d.kind === 'model').length,
      enums: ir.decls.filter(d => d.kind === 'enum').length,
      aliases: ir.decls.filter(d => d.kind === 'alias').length,
      operations: ir.decls.filter(d => d.kind === 'operation').length,
    },
    files: [options.output, ...extraFiles.map(file => file.path), ...(options.emitIr ? [`${options.output}.ir.json`] : [])],
    diagnostics,
  }

  const files: TspGeneratedFile[] = [{
    path: options.output,
    content: source,
    sourcePlugin: PYDANTIC_PLUGIN_NAME,
    banner: PYDANTIC_GENERATED_BANNER,
    kind: 'models',
    exports: ir.decls.map(d => d.pyName).filter((name): name is string => typeof name === 'string'),
    metadata: { report },
  }]
  files.push(...extraFiles)
  if (options.emitIr) {
    files.push({
      path: `${options.output}.ir.json`,
      content: `${JSON.stringify(ir, null, 2)}\n`,
      sourcePlugin: PYDANTIC_PLUGIN_NAME,
      banner: '',
      kind: 'ir',
    })
  }
  return { files, report }
}
