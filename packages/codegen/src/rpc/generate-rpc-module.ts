/**
 * RPC contract → TypeScript module
 *
 * Emits the procedure type map (`<Name>Procedures`) and the contract data (`<name>Contract`) that
 * `createRpcClient` / `createRpcServer` of `@oa-sdk/rpc` consume. Input and output types are folded
 * from the contract schemas with the typegen algebra; component schemas that are still referenced
 * by `$ref` (recursive types) are emitted as local type aliases.
 */

import type { OasSchema } from '@oa-sdk/parser/browser'
import type { RpcContract, RpcProcedure } from '@oa-sdk/surface-ir'
import { formatJSDoc } from '../typegen/jsdoc.js'
import { schemaToTs } from '../typegen/schema-to-ts.js'
import { compareTypegenKeys } from '../typegen/stable-order.js'
import { typeNameFromRef } from '../typegen/type-names.js'
import { pascalCase, quoteTypeScriptString, toTypeScriptIdentifier } from '@oa-sdk/core/browser'

export type RpcModuleOptions = {
  /** Name prefix: `Api` emits `ApiProcedures` and `apiContract`. Default: `Api`. */
  name?: string
  /** Module the `RpcContract` type is imported from. Default: `@oa-sdk/rpc`. */
  runtimeImport?: string
  /** Add the auto-generated banner. Default: true. */
  banner?: boolean
}

const COMPONENT_SCHEMA_REF = /^#\/components\/schemas\/(.+)$/

export function generateRpcModule(contract: RpcContract, options: RpcModuleOptions = {}): string {
  const name = toTypeScriptIdentifier(pascalCase(options.name ?? 'Api'))
  const proceduresType = `${name}Procedures`
  const contractConst = `${name.charAt(0).toLowerCase()}${name.slice(1)}Contract`
  const runtimeImport = options.runtimeImport ?? '@oa-sdk/rpc'
  const lines: string[] = []

  if (options.banner !== false) {
    lines.push('// Auto-generated by @oa-sdk/codegen from the RPC contract. Do not edit.')
    lines.push(`// Contract version: ${contract.versionHash}`)
    lines.push('')
  }
  lines.push(`import type { RpcContract } from ${quoteTypeScriptString(runtimeImport)}`)
  lines.push('')

  for (const ref of collectComponentRefs(contract)) {
    const componentName = ref.match(COMPONENT_SCHEMA_REF)![1]!
    const schema = contract.schemas[decodePointerToken(componentName)]
    if (!schema) continue
    if (schema.description) lines.push(formatJSDoc(schema.description))
    lines.push(`export type ${typeNameFromRef(ref)} = ${schemaToTs(schema)}`)
    lines.push('')
  }

  lines.push(`export type ${proceduresType} = {`)
  const procedures = Object.values(contract.procedures)
    .sort((left, right) => compareTypegenKeys(left.name, right.name))
  for (const procedure of procedures) {
    const doc = procedureDoc(procedure)
    if (doc) lines.push(formatJSDoc(doc, '  '))
    lines.push(`  ${quoteTypeScriptString(procedure.name)}: {`)
    lines.push(`    input: ${indent(inputType(procedure.input), '    ')}`)
    lines.push(`    output: ${procedure.output === null ? 'void' : indent(schemaToTs(procedure.output), '    ')}`)
    lines.push('  }')
  }
  lines.push('}')
  lines.push('')
  lines.push(`export const ${contractConst}: RpcContract = ${JSON.stringify(contract, null, 2)}`)
  lines.push('')
  return lines.join('\n')
}

function inputType(schema: OasSchema): string {
  return Object.keys(schema.properties ?? {}).length === 0 && schema.additionalProperties === false
    ? 'Record<string, never>'
    : schemaToTs(schema)
}

function procedureDoc(procedure: RpcProcedure): string | undefined {
  const parts = [procedure.summary, procedure.description].filter((part): part is string => Boolean(part))
  const text = [...new Set(parts)].join('\n\n')
  const lines = [
    ...(text === '' ? [] : [text]),
    `${procedure.http.method.toUpperCase()} ${procedure.http.path}`,
    ...(procedure.deprecated ? ['@deprecated'] : []),
  ]
  return lines.join('\n')
}

/** Component schema references reachable from procedure schemas, closed over the components. */
function collectComponentRefs(contract: RpcContract): string[] {
  const refs = new Set<string>()
  const pending: unknown[] = Object.values(contract.procedures)
    .flatMap(procedure => [procedure.input, procedure.output])
  while (pending.length > 0) {
    const value = pending.pop()
    if (Array.isArray(value)) {
      pending.push(...value)
      continue
    }
    if (typeof value !== 'object' || value === null) continue
    for (const [key, entry] of Object.entries(value)) {
      if (key === '$ref' && typeof entry === 'string' && COMPONENT_SCHEMA_REF.test(entry) && !refs.has(entry)) {
        refs.add(entry)
        pending.push(contract.schemas[decodePointerToken(entry.match(COMPONENT_SCHEMA_REF)![1]!)])
      } else {
        pending.push(entry)
      }
    }
  }
  return [...refs].sort(compareTypegenKeys)
}

function decodePointerToken(token: string): string {
  return decodeURIComponent(token).replace(/~1/g, '/').replace(/~0/g, '~')
}

function indent(text: string, prefix: string): string {
  return text.replace(/\n/g, `\n${prefix}`)
}
