import type {
  OasDocument,
  OasMediaType,
  OasOperation,
  OasParameter,
  OasPathItem,
  OasRequestBody,
  OasResponse,
  OasSchema,
  Referenceable,
} from '@oa-sdk/parser'

type RecordValue = Record<string, unknown>
type HttpMethod = 'get' | 'put' | 'post' | 'delete' | 'options' | 'head' | 'patch' | 'trace' | 'query'

const HTTP_METHODS: readonly HttpMethod[] = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace', 'query']
const IDENTIFIER_RE = /^[A-Za-z_][A-Za-z0-9_]*$/

export type TspExportDiagnosticSeverity = 'warning'

export type TspExportDiagnostic = {
  severity: TspExportDiagnosticSeverity
  code: string
  pointer: string
  message: string
}

export type TspExportReport = {
  schemaVersion: 'oa-gen.tsp-export-report.v1'
  namespace: string
  sourceOpenapi: string | null
  counts: {
    componentSchemas: number
    generatedModels: number
    operations: number
    diagnostics: number
  }
  diagnostics: TspExportDiagnostic[]
}

export type TspExportOptions = {
  namespace?: string
}

export type TspExportResult = {
  source: string
  report: TspExportReport
  diagnostics: TspExportDiagnostic[]
}

type RenderedSchema = {
  type: string
  decorators: string[]
  defaultValue?: string
}

type RenderSchemaOptions = {
  includeMetadata?: boolean
  includeDefault?: boolean
  includeConstraints?: boolean
}

type EmitModelOptions = {
  reportSchemaDefault?: boolean
}

type ResponseModel = {
  name: string
  lines: string[]
}

type OperationEmit = {
  lines: string[]
  responseModels: ResponseModel[]
}

export function exportOpenApiToTypeSpec(document: OasDocument, options: TspExportOptions = {}): TspExportResult {
  const exporter = new TypeSpecExporter(document, options)
  return exporter.export()
}

class TypeSpecExporter {
  private readonly diagnostics: TspExportDiagnostic[] = []
  private readonly componentNameBySchemaName = new Map<string, string>()
  private readonly usedTypeNames = new Set<string>()
  private readonly generatedModelDeclarations: string[][] = []
  private readonly responseModels: ResponseModel[] = []
  private operationCount = 0

  constructor(
    private readonly document: OasDocument,
    private readonly options: TspExportOptions,
  ) {}

  export(): TspExportResult {
    const namespace = this.options.namespace ?? toTypeName(this.document.info?.title ?? 'OaSdk')
    const schemaEntries = Object.entries(this.document.components?.schemas ?? {})
    for (const [schemaName] of schemaEntries) {
      this.componentNameBySchemaName.set(schemaName, this.reserveTypeName(schemaName))
    }

    const lines: string[] = [
      'import "@typespec/http";',
      'import "@typespec/openapi";',
      '',
      'using Http;',
      'using OpenAPI;',
      '',
      '// Generated by oa-gen tsp-export from an OpenAPI artifact.',
      '// Review the diagnostics report before treating this as canonical TypeSpec source.',
    ]

    lines.push(...this.emitNamespaceDecorators(namespace))
    lines.push(`namespace ${namespace};`)
    lines.push('')

    const componentDeclarations = schemaEntries.flatMap(([schemaName, schema]) => {
      const typeName = this.componentNameBySchemaName.get(schemaName) ?? this.reserveTypeName(schemaName)
      return this.emitNamedSchema(typeName, schema as OasSchema, `#/components/schemas/${escapeJsonPointer(schemaName)}`)
    })

    const operations = this.emitOperations()
    const declarations = [
      ...componentDeclarations,
      ...this.generatedModelDeclarations.flat(),
      ...this.responseModels.flatMap(model => model.lines),
      ...operations,
    ]

    lines.push(...declarations)

    this.reportDocumentLevelLosses()

    const source = `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
    const report: TspExportReport = {
      schemaVersion: 'oa-gen.tsp-export-report.v1',
      namespace,
      sourceOpenapi: typeof this.document.openapi === 'string' ? this.document.openapi : null,
      counts: {
        componentSchemas: schemaEntries.length,
        generatedModels: this.generatedModelDeclarations.length + this.responseModels.length,
        operations: this.operationCount,
        diagnostics: this.diagnostics.length,
      },
      diagnostics: this.diagnostics,
    }
    return { source, report, diagnostics: this.diagnostics }
  }

  private emitNamespaceDecorators(namespace: string): string[] {
    const lines: string[] = []
    for (const server of this.document.servers ?? []) {
      if (!server || typeof server.url !== 'string') continue
      const args = [quote(server.url)]
      if (typeof server.description === 'string' && server.description.length > 0) args.push(quote(server.description))
      lines.push(`@server(${args.join(', ')})`)
    }
    const title = this.document.info?.title ?? namespace
    lines.push(`@service(#{ title: ${quote(title)} })`)
    const version = this.document.info?.version ?? '0.0.0'
    lines.push(`@info(#{ version: ${quote(version)} })`)
    return lines
  }

  private emitNamedSchema(typeName: string, schema: OasSchema, pointer: string): string[] {
    if (this.isObjectSchema(schema)) {
      return this.emitModel(typeName, schema, pointer)
    }
    if (schema.default !== undefined) {
      this.addDefaultUnsupportedDiagnostic(`${pointer}/default`, 'Top-level schema defaults cannot be emitted as TypeSpec alias initializers yet.')
    }
    const rendered = this.renderSchema(schema, `${typeName}Value`, pointer, { includeDefault: false })
    return [
      ...rendered.decorators,
      `alias ${typeName} = ${rendered.type};`,
      '',
    ]
  }

  private emitModel(typeName: string, schema: OasSchema, pointer: string, options: EmitModelOptions = {}): string[] {
    this.reportSchemaLosses(schema, pointer)
    if ((options.reportSchemaDefault ?? true) && schema.default !== undefined) {
      this.addDefaultUnsupportedDiagnostic(`${pointer}/default`, 'Object schema defaults cannot be emitted as TypeSpec model initializers yet.')
    }
    const lines: string[] = [
      ...this.emitDecoratorsForSchema(schema, pointer),
      `model ${typeName} {`,
    ]
    const required = new Set(Array.isArray(schema.required) ? schema.required : [])
    const properties = schema.properties ?? {}
    for (const [propertyName, propertySchema] of Object.entries(properties)) {
      const propertyPointer = `${pointer}/properties/${escapeJsonPointer(propertyName)}`
      const rendered = this.renderSchema(propertySchema, `${typeName}${toTypeName(propertyName)}`, propertyPointer)
      const optional = required.has(propertyName) ? '' : '?'
      const defaultValue = rendered.defaultValue ? ` = ${rendered.defaultValue}` : ''
      for (const decorator of rendered.decorators) lines.push(`  ${decorator}`)
      lines.push(`  ${formatPropertyName(propertyName)}${optional}: ${rendered.type}${defaultValue};`)
    }
    if (schema.additionalProperties === false) {
      lines.push('  ...Record<never>;')
    }
    lines.push('}', '')
    return lines
  }

  private emitOperations(): string[] {
    const lines: string[] = []
    const paths = this.document.paths ?? {}
    for (const [path, pathItemValue] of Object.entries(paths)) {
      if (!isRecord(pathItemValue) || isReference(pathItemValue)) {
        this.addDiagnostic('path/ref-skipped', `#/paths/${escapeJsonPointer(path)}`, 'Path item references are not expanded by tsp-export.')
        continue
      }
      const pathItem = pathItemValue as OasPathItem
      for (const method of HTTP_METHODS) {
        const operation = pathItem[method]
        if (!operation) continue
        const emitted = this.emitOperation(path, method, pathItem, operation, `#/paths/${escapeJsonPointer(path)}/${method}`)
        this.responseModels.push(...emitted.responseModels)
        lines.push(...emitted.lines)
      }
    }
    return lines
  }

  private emitOperation(
    path: string,
    method: HttpMethod,
    pathItem: OasPathItem,
    operation: OasOperation,
    pointer: string,
  ): OperationEmit {
    this.operationCount += 1
    const operationId = operation.operationId ?? `${method}${toTypeName(path)}`
    const operationName = toValueName(operationId)
    const responseModels = this.emitResponseModels(operationId, operation, pointer)
    const returnType = responseModels.length > 0 ? responseModels.map(model => model.name).join(' | ') : 'void'
    const parameters = this.emitOperationParameters(pathItem, operation, operationId, pointer)
    const requestBody = this.emitRequestBodyParameter(operationId, operation.requestBody, `${pointer}/requestBody`)
    if (requestBody) parameters.push(requestBody)

    const decorators = [
      ...this.emitDecoratorsForDescription(operation.summary, operation.description),
      ...(operation.tags ?? []).map(tag => `@tag(${quote(tag)})`),
      `@operationId(${quote(operationId)})`,
      `@route(${quote(path)})`,
      `@${method}`,
    ]

    if (operation.security) {
      this.addDiagnostic('operation/security-dropped', `${pointer}/security`, 'Operation security requirements need a TypeSpec auth model and were not emitted.')
    }
    if (operation.callbacks) {
      this.addDiagnostic('operation/callbacks-dropped', `${pointer}/callbacks`, 'OpenAPI callbacks were not emitted to TypeSpec.')
    }

    const signature = parameters.length > 0
      ? `op ${operationName}(\n${parameters.map(param => `  ${param}`).join(',\n')},\n): ${returnType};`
      : `op ${operationName}(): ${returnType};`

    return {
      responseModels,
      lines: [
        ...decorators,
        signature,
        '',
      ],
    }
  }

  private emitOperationParameters(
    pathItem: OasPathItem,
    operation: OasOperation,
    operationId: string,
    pointer: string,
  ): string[] {
    const merged = new Map<string, { parameter: OasParameter; pointer: string }>()
    for (const [scope, list] of [['path', pathItem.parameters], ['operation', operation.parameters]] as const) {
      for (let index = 0; index < (list?.length ?? 0); index += 1) {
        const parameterPointer = scope === 'path'
          ? `${pointer.replace(/\/[^/]+$/, '')}/parameters/${index}`
          : `${pointer}/parameters/${index}`
        const parameter = this.resolveReference<OasParameter>(list?.[index], parameterPointer)
        if (!parameter) continue
        merged.set(`${parameter.in}:${parameter.name}`, { parameter, pointer: parameterPointer })
      }
    }

    return [...merged.values()].map(({ parameter, pointer: parameterPointer }) => {
      const schema = parameter.schema
      const rendered = schema
        ? this.renderSchema(schema as OasSchema, `${toTypeName(operationId)}${toTypeName(parameter.name)}Param`, `${parameterPointer}/schema`, { includeMetadata: false })
        : { type: 'unknown', decorators: [] }
      const location = parameter.in === 'path' || parameter.in === 'query' || parameter.in === 'header' || parameter.in === 'cookie'
        ? parameter.in
        : 'query'
      const locationDecorator = parameter.name === toValueName(parameter.name)
        ? `@${location}`
        : `@${location}(${quote(parameter.name)})`
      const docs = this.emitDecoratorsForDescription(undefined, parameter.description)
      const decorators = [...docs, locationDecorator, ...rendered.decorators]
      const optional = parameter.required || parameter.in === 'path' ? '' : '?'
      if (parameter.example !== undefined || parameter.examples !== undefined) {
        this.addDiagnostic('parameter/examples-dropped', parameterPointer, 'Parameter examples are not emitted to TypeSpec.')
      }
      const defaultValue = rendered.defaultValue ? ` = ${rendered.defaultValue}` : ''
      return `${decorators.join(' ')} ${toValueName(parameter.name)}${optional}: ${rendered.type}${defaultValue}`
    })
  }

  private emitRequestBodyParameter(operationId: string, requestBodyValue: Referenceable<OasRequestBody> | undefined, pointer: string): string | null {
    if (!requestBodyValue) return null
    const requestBody = this.resolveReference<OasRequestBody>(requestBodyValue, pointer)
    if (!requestBody) return null
    const content = requestBody.content ?? {}
    const mediaType = content['application/json'] ? 'application/json' : Object.keys(content)[0]
    if (!mediaType) {
      this.addDiagnostic('request-body/content-missing', pointer, 'Request body has no content schema to emit.')
      return null
    }
    if (mediaType !== 'application/json') {
      this.addDiagnostic('request-body/media-type-dropped', `${pointer}/content/${escapeJsonPointer(mediaType)}`, `Only the schema is emitted; media type ${mediaType} is not preserved.`)
    }
    const mediaTypeObject = this.resolveReference<OasMediaType>(content[mediaType], `${pointer}/content/${escapeJsonPointer(mediaType)}`)
    if (!mediaTypeObject) return null
    const schema = mediaTypeObject.schema
    if (!schema) {
      this.addDiagnostic('request-body/schema-missing', `${pointer}/content/${escapeJsonPointer(mediaType)}`, 'Request body media type has no schema.')
      return null
    }
    const rendered = this.renderSchema(schema as OasSchema, `${toTypeName(operationId)}RequestBody`, `${pointer}/content/${escapeJsonPointer(mediaType)}/schema`, { includeMetadata: false })
    const decorators = [
      ...this.emitDecoratorsForDescription(undefined, requestBody.description),
      '@body',
      ...rendered.decorators,
    ]
    const optional = requestBody.required ? '' : '?'
    const defaultValue = rendered.defaultValue ? ` = ${rendered.defaultValue}` : ''
    return `${decorators.join(' ')} body${optional}: ${rendered.type}${defaultValue}`
  }

  private emitResponseModels(operationId: string, operation: OasOperation, pointer: string): ResponseModel[] {
    const responses = operation.responses ?? {}
    const models: ResponseModel[] = []
    for (const [statusCode, responseValue] of Object.entries(responses)) {
      const responsePointer = `${pointer}/responses/${escapeJsonPointer(statusCode)}`
      if (!/^[1-5][0-9][0-9]$/.test(statusCode)) {
        this.addDiagnostic('response/status-unsupported', responsePointer, `Response status ${statusCode} is not emitted as a TypeSpec response model.`)
        continue
      }
      const response = this.resolveReference<OasResponse>(responseValue, responsePointer)
      if (!response) continue
      const modelName = this.reserveTypeName(`${toTypeName(operationId)}${statusCode}Response`)
      const lines = [
        ...this.emitDecoratorsForDescription(undefined, response.description),
        `model ${modelName} {`,
        `  @statusCode statusCode: ${statusCode};`,
      ]
      const body = this.renderResponseBody(operationId, statusCode, response, responsePointer)
      if (body) {
        for (const decorator of body.decorators) lines.push(`  ${decorator}`)
        const defaultValue = body.defaultValue ? ` = ${body.defaultValue}` : ''
        lines.push(`  @body body: ${body.type}${defaultValue};`)
      }
      if (response.headers) {
        this.addDiagnostic('response/headers-dropped', `${responsePointer}/headers`, 'Response headers are not emitted to TypeSpec response models yet.')
      }
      if (response.links) {
        this.addDiagnostic('response/links-dropped', `${responsePointer}/links`, 'OpenAPI links are not emitted to TypeSpec response models.')
      }
      lines.push('}', '')
      models.push({ name: modelName, lines })
    }
    return models
  }

  private renderResponseBody(operationId: string, statusCode: string, response: OasResponse, pointer: string): RenderedSchema | null {
    const content = response.content ?? {}
    const mediaType = content['application/json'] ? 'application/json' : Object.keys(content)[0]
    if (!mediaType) return null
    if (mediaType !== 'application/json') {
      this.addDiagnostic('response/media-type-dropped', `${pointer}/content/${escapeJsonPointer(mediaType)}`, `Only the response body schema is emitted; media type ${mediaType} is not preserved.`)
    }
    const mediaTypeObject = this.resolveReference<OasMediaType>(content[mediaType], `${pointer}/content/${escapeJsonPointer(mediaType)}`)
    if (!mediaTypeObject) return null
    const schema = mediaTypeObject.schema
    if (!schema) {
      this.addDiagnostic('response/schema-missing', `${pointer}/content/${escapeJsonPointer(mediaType)}`, 'Response media type has no schema.')
      return null
    }
    if (mediaTypeObject.example !== undefined || mediaTypeObject.examples !== undefined) {
      this.addDiagnostic('response/examples-dropped', `${pointer}/content/${escapeJsonPointer(mediaType)}`, 'Response examples are not emitted to TypeSpec.')
    }
    return this.renderSchema(schema as OasSchema, `${toTypeName(operationId)}${statusCode}Body`, `${pointer}/content/${escapeJsonPointer(mediaType)}/schema`)
  }

  private renderSchema(schema: OasSchema, contextName: string, pointer: string, options: RenderSchemaOptions = {}): RenderedSchema {
    const includeMetadata = options.includeMetadata ?? true
    const includeDefault = options.includeDefault ?? true
    const includeConstraints = options.includeConstraints ?? true
    this.reportSchemaLosses(schema, pointer)
    const decorators = [
      ...(includeMetadata ? this.emitDecoratorsForSchema(schema, pointer) : []),
      ...(includeConstraints ? this.emitConstraintDecorators(schema) : []),
    ]
    const defaultValue = includeDefault ? this.emitDefaultValueForSchema(schema, pointer) : undefined
    const rendered = (type: string, schemaDecorators = decorators): RenderedSchema => ({
      type,
      decorators: schemaDecorators,
      ...(defaultValue !== undefined ? { defaultValue } : {}),
    })
    if (schema.$ref) {
      const refName = this.localSchemaRefName(schema.$ref, pointer)
      return rendered(refName ?? 'unknown')
    }
    if (schema.const !== undefined) return rendered(literal(schema.const))
    if (Array.isArray(schema.enum) && schema.enum.length > 0) {
      return rendered(schema.enum.map(value => literal(value)).join(' | '))
    }

    const typeValue = schema.type
    if (Array.isArray(typeValue)) {
      const nonNullTypes = typeValue.filter(type => type !== 'null')
      const nonNullSchema: OasSchema = { ...schema }
      const onlyType = nonNullTypes[0]
      if (nonNullTypes.length === 1 && onlyType) {
        nonNullSchema.type = onlyType
      } else if (nonNullTypes.length > 1) {
        nonNullSchema.type = nonNullTypes
      } else {
        delete nonNullSchema.type
      }
      const nonNullRendered = this.renderSchema(nonNullSchema, contextName, pointer, {
        includeMetadata: false,
        includeDefault: false,
        includeConstraints: false,
      })
      return rendered(typeValue.includes('null') ? `${nonNullRendered.type} | null` : nonNullRendered.type)
    }

    if (typeValue === 'array') {
      const item = schema.items
        ? this.renderSchema(schema.items, `${contextName}Item`, `${pointer}/items`, {
          includeMetadata: false,
          includeDefault: false,
        })
        : { type: 'unknown', decorators: [] }
      return rendered(`${item.type}[]`, [...decorators, ...item.decorators])
    }

    if (typeValue === 'object' || schema.properties) {
      const inlineName = this.reserveTypeName(contextName)
      const lines = this.emitModel(inlineName, schema, pointer, { reportSchemaDefault: false })
      this.generatedModelDeclarations.push(lines)
      return rendered(inlineName)
    }

    if (schema.allOf && schema.allOf.length > 0) {
      return rendered(schema.allOf.map((item, index) => this.renderSchema(item, `${contextName}AllOf${index + 1}`, `${pointer}/allOf/${index}`, {
        includeMetadata: false,
        includeDefault: false,
      }).type).join(' & '))
    }
    if (schema.oneOf && schema.oneOf.length > 0) {
      return rendered(schema.oneOf.map((item, index) => this.renderSchema(item, `${contextName}OneOf${index + 1}`, `${pointer}/oneOf/${index}`, {
        includeMetadata: false,
        includeDefault: false,
      }).type).join(' | '))
    }
    if (schema.anyOf && schema.anyOf.length > 0) {
      return rendered(schema.anyOf.map((item, index) => this.renderSchema(item, `${contextName}AnyOf${index + 1}`, `${pointer}/anyOf/${index}`, {
        includeMetadata: false,
        includeDefault: false,
      }).type).join(' | '))
    }

    if (typeValue === 'string') {
      if (schema.format === 'date-time') return rendered('utcDateTime')
      if (schema.format === 'date') return rendered('plainDate')
      return rendered('string')
    }
    if (typeValue === 'integer') return rendered(schema.format === 'int64' ? 'int64' : 'int32')
    if (typeValue === 'number') return rendered(schema.format === 'float' ? 'float32' : 'float64')
    if (typeValue === 'boolean') return rendered('boolean')
    if (typeValue === 'null') return rendered('null')

    this.addDiagnostic('schema/type-unknown', pointer, 'Schema type could not be mapped precisely and was emitted as unknown.')
    return rendered('unknown')
  }

  private emitDecoratorsForSchema(schema: OasSchema, pointer: string): string[] {
    const decorators = this.emitDecoratorsForDescription(undefined, schema.description)
    if (schema.deprecated) {
      decorators.push('#deprecated "Deprecated"')
    }
    return decorators
  }

  private emitDefaultValueForSchema(schema: OasSchema, pointer: string): string | undefined {
    if (schema.default === undefined) return undefined
    const value = typeSpecValueLiteral(schema.default)
    if (value !== undefined) return value
    this.addDefaultUnsupportedDiagnostic(`${pointer}/default`, 'Schema default is not a JSON-compatible TypeSpec value literal and was not emitted.')
    return undefined
  }

  private emitConstraintDecorators(schema: OasSchema): string[] {
    const decorators: string[] = []
    if (schema.format && schema.type === 'string' && schema.format !== 'date-time' && schema.format !== 'date') {
      decorators.push(`@format(${quote(schema.format)})`)
    }
    if (typeof schema.minLength === 'number') decorators.push(`@minLength(${schema.minLength})`)
    if (typeof schema.maxLength === 'number') decorators.push(`@maxLength(${schema.maxLength})`)
    if (typeof schema.minimum === 'number') decorators.push(`@minValue(${schema.minimum})`)
    if (typeof schema.maximum === 'number') decorators.push(`@maxValue(${schema.maximum})`)
    if (typeof schema.pattern === 'string') decorators.push(`@pattern(${quote(schema.pattern)})`)
    return decorators
  }

  private emitDecoratorsForDescription(summary: string | undefined, description: string | undefined): string[] {
    const decorators: string[] = []
    if (summary) decorators.push(`@summary(${quote(summary)})`)
    if (description) decorators.push(`@doc(${quote(description)})`)
    return decorators
  }

  private resolveReference<T>(value: Referenceable<T> | undefined, pointer: string): T | undefined {
    if (!value) return undefined
    if (!isReference(value)) return value as T
    const resolved = this.resolveLocalRef(value.$ref)
    if (!resolved) {
      this.addDiagnostic('ref/unresolved', pointer, `Could not resolve local reference ${value.$ref}.`)
      return undefined
    }
    return resolved as T
  }

  private resolveLocalRef(ref: string): unknown {
    if (!ref.startsWith('#/')) return undefined
    const parts = ref.slice(2).split('/').map(unescapeJsonPointer)
    let current: unknown = this.document
    for (const part of parts) {
      if (!isRecord(current)) return undefined
      current = current[part]
    }
    return current
  }

  private localSchemaRefName(ref: string, pointer: string): string | undefined {
    const prefix = '#/components/schemas/'
    if (!ref.startsWith(prefix)) {
      this.addDiagnostic('schema/ref-nonlocal', pointer, `Only local component schema refs are emitted precisely. Got ${ref}.`)
      return undefined
    }
    const schemaName = unescapeJsonPointer(ref.slice(prefix.length))
    const mapped = this.componentNameBySchemaName.get(schemaName)
    if (!mapped) {
      this.addDiagnostic('schema/ref-missing', pointer, `Component schema ref not found: ${ref}.`)
    }
    return mapped
  }

  private isObjectSchema(schema: OasSchema): boolean {
    return schema.type === 'object' || Boolean(schema.properties)
  }

  private reserveTypeName(rawName: string): string {
    const base = toTypeName(rawName)
    let name = base
    let index = 2
    while (this.usedTypeNames.has(name)) {
      name = `${base}${index}`
      index += 1
    }
    this.usedTypeNames.add(name)
    return name
  }

  private reportDocumentLevelLosses(): void {
    if (this.document.security) {
      this.addDiagnostic('document/security-dropped', '#/security', 'Root security requirements need a TypeSpec auth model and were not emitted.')
    }
    if (this.document.components?.securitySchemes) {
      this.addDiagnostic('components/security-schemes-dropped', '#/components/securitySchemes', 'Security schemes are not emitted by the first tsp-export pass.')
    }
    if (this.document.tags?.some(tag => tag.description)) {
      this.addDiagnostic('tags/metadata-dropped', '#/tags', 'Tag descriptions are not emitted as TypeSpec tag metadata yet.')
    }
    if (this.document.jsonSchemaDialect) {
      this.addDiagnostic('document/json-schema-dialect-dropped', '#/jsonSchemaDialect', 'jsonSchemaDialect is OpenAPI-level metadata and was not emitted to TypeSpec.')
    }
  }

  private reportSchemaLosses(schema: OasSchema, pointer: string): void {
    if (schema.example !== undefined || schema.examples !== undefined) this.addDiagnostic('schema/examples-dropped', pointer, 'Schema examples are not emitted to TypeSpec yet.')
    if (schema.readOnly || schema.writeOnly) this.addDiagnostic('schema/visibility-dropped', pointer, 'readOnly/writeOnly need a visibility policy and were not emitted.')
    if (schema.discriminator) this.addDiagnostic('schema/discriminator-dropped', `${pointer}/discriminator`, 'Discriminator metadata is not emitted to TypeSpec yet.')
    if (schema.additionalProperties !== undefined && schema.additionalProperties !== false) {
      this.addDiagnostic('schema/additional-properties-dropped', `${pointer}/additionalProperties`, 'additionalProperties is not emitted to TypeSpec yet.')
    }
    if (schema.patternProperties) this.addDiagnostic('schema/pattern-properties-dropped', `${pointer}/patternProperties`, 'patternProperties is not emitted to TypeSpec yet.')
    if (schema.not || schema.if || schema.then || schema.else) this.addDiagnostic('schema/conditional-dropped', pointer, 'not/if/then/else schema constraints are not emitted to TypeSpec yet.')
  }

  private addDefaultUnsupportedDiagnostic(pointer: string, message: string): void {
    this.addDiagnostic('schema/default-unsupported', pointer, message)
  }

  private addDiagnostic(code: string, pointer: string, message: string): void {
    this.diagnostics.push({ severity: 'warning', code, pointer, message })
  }
}

function isRecord(value: unknown): value is RecordValue {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function isReference(value: unknown): value is { $ref: string } {
  return isRecord(value) && typeof value.$ref === 'string'
}

function quote(value: string): string {
  return JSON.stringify(value)
}

function literal(value: unknown): string {
  if (typeof value === 'string') return quote(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (value === null) return 'null'
  return 'unknown'
}

function typeSpecValueLiteral(value: unknown): string | undefined {
  if (typeof value === 'string') return quote(value)
  if (typeof value === 'boolean') return String(value)
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : undefined
  if (value === null) return 'null'
  if (Array.isArray(value)) {
    const items = value.map(typeSpecValueLiteral)
    if (items.some(item => item === undefined)) return undefined
    return `#[${items.join(', ')}]`
  }
  if (isRecord(value)) {
    const entries = Object.entries(value)
      .map(([key, entry]) => {
        if (!IDENTIFIER_RE.test(key)) return undefined
        const literalValue = typeSpecValueLiteral(entry)
        return literalValue === undefined ? undefined : `${key}: ${literalValue}`
      })
    if (entries.some(entry => entry === undefined)) return undefined
    return `#{${entries.length > 0 ? ` ${entries.join(', ')} ` : ''}}`
  }
  return undefined
}

function toTypeName(raw: string): string {
  const fallback = raw.trim().length > 0 ? raw : 'Generated'
  const words = fallback
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
  const name = words.length > 0
    ? words.map(word => `${word[0]?.toUpperCase() ?? ''}${word.slice(1)}`).join('')
    : 'Generated'
  return IDENTIFIER_RE.test(name) && /^[A-Z_]/.test(name) ? name : `Generated${name.replace(/^[^A-Za-z_]+/, '')}`
}

function toValueName(raw: string): string {
  const typeName = toTypeName(raw)
  const candidate = `${typeName[0]?.toLowerCase() ?? 'v'}${typeName.slice(1)}`
  return IDENTIFIER_RE.test(candidate) ? candidate : 'value'
}

function formatPropertyName(name: string): string {
  return IDENTIFIER_RE.test(name) ? name : quote(name)
}

function escapeJsonPointer(value: string): string {
  return value.replace(/~/g, '~0').replace(/\//g, '~1')
}

function unescapeJsonPointer(value: string): string {
  return value.replace(/~1/g, '/').replace(/~0/g, '~')
}
