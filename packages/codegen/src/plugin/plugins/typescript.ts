import { formatGeneratedTs, pascalCase } from '@oa-sdk/core'
import type { OasDocument, OasSchema } from '@oa-sdk/parser'
import { generateTypesFromSpec } from '../../typegen/generate-types.js'
import type { TspPlugin, TspPluginContext } from '../types.js'

export interface PluginTypescriptOptions {
  /** Output file relative path. Default: 'types.ts' */
  output?: string | undefined
  /** Enum representation: 'union' (type X = 'a' | 'b'), 'typescript' (enum X {}), 'javascript' */
  enums?: 'union' | 'typescript' | 'javascript' | undefined
  /** Whether to generate standalone runtime type guards. Default: false */
  typeGuards?: boolean | undefined
  /** Output file for standalone type guards if enabled. Default: 'guards.ts' */
  guardsOutput?: string | undefined
  /** Whether to emit JSDoc comments from TypeSpec @doc. Default: true */
  comments?: boolean | undefined
  /** Export format: 'named' or 'type-only' */
  exportFormat?: 'named' | 'type-only' | undefined
  /** Interface or type alias: 'interface' | 'type'. Default: 'type' */
  style?: 'interface' | 'type' | undefined
}

/**
 * Transforms string union type definitions into TypeScript enum declarations
 * or JavaScript const objects according to the enums option.
 */
function applyEnumTransformations(
  code: string,
  doc: OasDocument,
  enumMode: 'union' | 'typescript' | 'javascript',
): string {
  if (enumMode === 'union') {
    return code
  }

  let transformed = code
  const schemas = (doc.components?.schemas ?? {}) as Record<string, OasSchema>

  for (const [name, schema] of Object.entries(schemas)) {
    if (schema && Array.isArray(schema.enum) && schema.enum.length > 0) {
      const typeDefRegex = new RegExp(`export type ${name} = [^;\\n]+;?`, 'g')

      if (enumMode === 'typescript') {
        const members = schema.enum.map(val => {
          const key = pascalCase(String(val).replace(/[^a-zA-Z0-9_$]/g, '_')) || 'Value'
          const memberKey = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : `'${key}'`
          return `  ${memberKey} = ${JSON.stringify(val)},`
        }).join('\n')

        const enumDef = `export enum ${name} {\n${members}\n}`
        transformed = transformed.replace(typeDefRegex, enumDef)
      } else if (enumMode === 'javascript') {
        const members = schema.enum.map(val => {
          const key = pascalCase(String(val).replace(/[^a-zA-Z0-9_$]/g, '_')) || 'Value'
          const memberKey = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : `'${key}'`
          return `  ${memberKey}: ${JSON.stringify(val)},`
        }).join('\n')

        const constDef = `export const ${name} = {\n${members}\n} as const;\nexport type ${name} = (typeof ${name})[keyof typeof ${name}];`
        transformed = transformed.replace(typeDefRegex, constDef)
      }
    }
  }

  return transformed
}

/**
 * Extracts exported type, interface, enum, or const identifiers from generated TypeScript source.
 */
function extractExportedSymbols(code: string): string[] {
  const exports = new Set<string>()
  const regex = /export\s+(?:type|interface|enum|const|function)\s+([A-Za-z0-9_$]+)/g
  let match: RegExpExecArray | null

  while ((match = regex.exec(code)) !== null) {
    if (match[1]) {
      exports.add(match[1])
    }
  }

  return Array.from(exports).sort()
}

/**
 * Generates standalone, zero-eval runtime type guard functions for schemas.
 */
function generateRuntimeTypeGuards(
  doc: OasDocument,
  typesImportSpecifier: string,
): { code: string; exports: string[] } {
  const schemas = (doc.components?.schemas ?? {}) as Record<string, OasSchema>
  const schemaEntries = Object.entries(schemas)
  const lines: string[] = [
    '// @generated by @oa-sdk/codegen (standalone runtime type guards). DO NOT EDIT.',
    '',
  ]

  const typeNamesToImport: string[] = []
  const guardFunctions: string[] = []
  const exportedGuards: string[] = []

  for (const [name, schema] of schemaEntries) {
    if (!schema || typeof schema !== 'object') continue

    const guardName = `is${pascalCase(name)}`
    exportedGuards.push(guardName)
    typeNamesToImport.push(name)

    if (Array.isArray(schema.enum) && schema.enum.length > 0) {
      const condition = schema.enum.map(val => `value === ${JSON.stringify(val)}`).join(' || ')
      guardFunctions.push(`export function ${guardName}(value: unknown): value is ${name} {\n  return ${condition};\n}\n`)
      continue
    }

    const checkLines: string[] = [
      '  if (typeof value !== \'object\' || value === null) return false;',
      '  const v = value as Record<string, unknown>;',
    ]

    const requiredFields = new Set<string>(Array.isArray(schema.required) ? schema.required : [])
    const properties = (schema.properties ?? {}) as Record<string, OasSchema>

    for (const [propName, propSchema] of Object.entries(properties)) {
      const isReq = requiredFields.has(propName)
      const propAccess = `v[${JSON.stringify(propName)}]`

      if (isReq) {
        if (propSchema.type === 'string') {
          checkLines.push(`  if (typeof ${propAccess} !== 'string') return false;`)
        } else if (propSchema.type === 'number' || propSchema.type === 'integer') {
          checkLines.push(`  if (typeof ${propAccess} !== 'number') return false;`)
        } else if (propSchema.type === 'boolean') {
          checkLines.push(`  if (typeof ${propAccess} !== 'boolean') return false;`)
        } else if (propSchema.type === 'array') {
          checkLines.push(`  if (!Array.isArray(${propAccess})) return false;`)
        } else {
          checkLines.push(`  if (${propAccess} === undefined) return false;`)
        }
      } else {
        if (propSchema.type === 'string') {
          checkLines.push(`  if (${propAccess} !== undefined && typeof ${propAccess} !== 'string') return false;`)
        } else if (propSchema.type === 'number' || propSchema.type === 'integer') {
          checkLines.push(`  if (${propAccess} !== undefined && typeof ${propAccess} !== 'number') return false;`)
        } else if (propSchema.type === 'boolean') {
          checkLines.push(`  if (${propAccess} !== undefined && typeof ${propAccess} !== 'boolean') return false;`)
        } else if (propSchema.type === 'array') {
          checkLines.push(`  if (${propAccess} !== undefined && !Array.isArray(${propAccess})) return false;`)
        }
      }
    }

    checkLines.push('  return true;')
    guardFunctions.push(`export function ${guardName}(value: unknown): value is ${name} {\n${checkLines.join('\n')}\n}\n`)
  }

  if (typeNamesToImport.length > 0) {
    lines.push(`import type { ${typeNamesToImport.sort().join(', ')} } from '${typesImportSpecifier}';`)
    lines.push('')
  }

  lines.push(...guardFunctions)

  return {
    code: formatGeneratedTs(lines.join('\n')),
    exports: exportedGuards.sort(),
  }
}

/**
 * Core plugin for generating pure TypeScript models, enums, DTOs, and standalone type guards.
 */
export function pluginTypescript(options: PluginTypescriptOptions = {}): TspPlugin<PluginTypescriptOptions> {
  return {
    name: 'typescript',
    dependencies: [],
    generate: (context: TspPluginContext, hookOptions?: PluginTypescriptOptions) => {
      const merged: PluginTypescriptOptions = { ...options, ...hookOptions }
      const outputPath = merged.output ?? 'types.ts'

      // Generate base TypeScript types and models
      let code = generateTypesFromSpec(context.document, {
        style: merged.style ?? 'type',
        includeAnnotations: merged.comments !== false,
        banner: true,
      })

      // Apply enum style transformations
      if (merged.enums && merged.enums !== 'union') {
        code = applyEnumTransformations(code, context.document, merged.enums)
      }

      // Strip comments if explicitly disabled
      if (merged.comments === false) {
        code = code.replace(/\/\*\*[\s\S]*?\*\/\s*/g, '')
      }

      const formattedCode = formatGeneratedTs(code)
      const exports = extractExportedSymbols(formattedCode)

      context.addFile({
        path: outputPath,
        content: formattedCode,
        sourcePlugin: 'typescript',
        exports,
        kind: 'models',
      })

      context.setPluginData('typescript:output', outputPath)
      context.setPluginData('typescript:exports', exports)

      // Optionally generate standalone runtime type guards
      if (merged.typeGuards === true) {
        const guardsPath = merged.guardsOutput ?? 'guards.ts'
        const typesImportSpecifier = context.resolveImport(guardsPath, outputPath)
        const { code: guardsCode, exports: guardExports } = generateRuntimeTypeGuards(
          context.document,
          typesImportSpecifier,
        )

        context.addFile({
          path: guardsPath,
          content: guardsCode,
          sourcePlugin: 'typescript',
          exports: guardExports,
          kind: 'guards',
        })

        context.setPluginData('typescript:guardsOutput', guardsPath)
        context.setPluginData('typescript:guardsExports', guardExports)
      }
    },
  }
}
