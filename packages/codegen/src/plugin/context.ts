import { posix } from 'node:path'
import type { Program } from '@typespec/compiler'
import { parseDocument, type OasDocument, type ParsedDocument } from '@oa-sdk/parser'
import type { SurfaceIr } from '@oa-sdk/surface-ir'
import {
  type TspConfig,
  type TspGeneratedFile,
  type TspPluginContext,
  type TspPluginDiagnostic,
  TspFileConflictError,
} from './types.js'

export interface CreatePluginContextOptions {
  /** Resolved entrypoint path (.tsp) */
  entrypoint: string
  /** Resolved output directory */
  outputDir: string
  /** OpenAPI 3.2 Document */
  document: OasDocument
  /** Optional in-memory TypeSpec Program */
  program?: Program | unknown | undefined
  /** Resolved configuration */
  config: TspConfig
  /** Target OpenAPI version */
  openApiVersion?: '3.0.0' | '3.1.0' | '3.2.0' | undefined
  /** Optional Surface IR */
  surfaceIR?: SurfaceIr | undefined
}

/**
 * Normalizes a virtual file path to a clean relative POSIX path.
 */
export function normalizeVirtualPath(filePath: string): string {
  const clean = filePath.replace(/\\/g, '/').trim()
  return posix.normalize(clean).replace(/^\.\//, '').replace(/^\//, '')
}

/**
 * Replaces TypeScript file extensions (.ts, .tsx, etc.) with .js for ESM imports.
 */
export function formatEsmImportExtension(specifier: string): string {
  const stripped = specifier.replace(/\.(?:[mc]?[jt]sx?)$/, '')
  return `${stripped}.js`
}

/**
 * Concrete implementation of TspPluginContext.
 */
export class TspPluginContextImpl implements TspPluginContext {
  public readonly entrypoint: string
  public readonly outputDir: string
  public readonly program?: Program | unknown | undefined
  public readonly document: OasDocument
  public readonly surfaceIR?: SurfaceIr | undefined
  public readonly config: TspConfig
  public readonly openApiVersion: '3.0.0' | '3.1.0' | '3.2.0'
  public readonly files = new Map<string, TspGeneratedFile>()
  public readonly sharedData = new Map<string, unknown>()
  private readonly _diagnostics: TspPluginDiagnostic[] = []
  private _parsed?: ParsedDocument

  constructor(options: CreatePluginContextOptions) {
    this.entrypoint = options.entrypoint
    this.outputDir = options.outputDir
    this.document = options.document
    this.program = options.program
    this.config = options.config
    this.openApiVersion = options.openApiVersion ?? options.config.openApiVersion ?? '3.2.0'
    this.surfaceIR = options.surfaceIR
  }

  /**
   * Lazily initialized ParsedDocument IR from @oa-sdk/parser.
   */
  get parsed(): ParsedDocument {
    if (!this._parsed) {
      this._parsed = parseDocument(this.document)
    }
    return this._parsed
  }

  get diagnostics(): readonly TspPluginDiagnostic[] {
    return this._diagnostics
  }

  addFile(file: TspGeneratedFile): void {
    const normalizedPath = normalizeVirtualPath(file.path)
    const existing = this.files.get(normalizedPath)

    if (existing && existing.sourcePlugin !== file.sourcePlugin) {
      throw new TspFileConflictError(normalizedPath, existing.sourcePlugin, file.sourcePlugin)
    }

    const banner = file.banner !== undefined ? file.banner : '// @generated by @oa-sdk/codegen. DO NOT EDIT.'

    this.files.set(normalizedPath, {
      ...file,
      path: normalizedPath,
      banner,
    })
  }

  getFile(path: string): TspGeneratedFile | undefined {
    return this.files.get(normalizeVirtualPath(path))
  }

  getFiles(): readonly TspGeneratedFile[] {
    return Array.from(this.files.values())
  }

  updateFile(path: string, updater: (existing: TspGeneratedFile) => TspGeneratedFile): void {
    const normalizedPath = normalizeVirtualPath(path)
    const existing = this.files.get(normalizedPath)

    if (!existing) {
      throw new Error(`Cannot update file "${normalizedPath}": file does not exist in context`)
    }

    const updated = updater(existing)
    const updatedNormPath = normalizeVirtualPath(updated.path)

    if (updatedNormPath !== normalizedPath) {
      this.files.delete(normalizedPath)
    }

    this.files.set(updatedNormPath, {
      ...updated,
      path: updatedNormPath,
    })
  }

  removeFile(path: string): boolean {
    return this.files.delete(normalizeVirtualPath(path))
  }

  hasFile(path: string): boolean {
    return this.files.has(normalizeVirtualPath(path))
  }

  resolveImport(fromFile: string, targetFile: string): string {
    const normFrom = normalizeVirtualPath(fromFile)
    const normTarget = normalizeVirtualPath(targetFile)

    if (normFrom.toLowerCase() === normTarget.toLowerCase()) {
      throw new Error(
        `Self-import is not allowed: cannot resolve import from "${fromFile}" to itself.`,
      )
    }

    const fromDir = posix.dirname(normFrom)
    let relative = posix.relative(fromDir, normTarget)

    if (!relative.startsWith('.')) {
      relative = `./${relative}`
    }

    return formatEsmImportExtension(relative)
  }

  setPluginData<T>(key: string, value: T): void {
    this.sharedData.set(key, value)
  }

  getPluginData<T>(key: string): T | undefined {
    return this.sharedData.get(key) as T | undefined
  }

  log(level: 'info' | 'warn' | 'error' | 'debug', message: string): void {
    if (level === 'error') {
      this.reportDiagnostic({ message, severity: 'error' })
    } else if (level === 'warn') {
      this.reportDiagnostic({ message, severity: 'warning' })
    }
  }

  reportDiagnostic(diagnostic: TspPluginDiagnostic): void {
    this._diagnostics.push(diagnostic)
  }
}

/**
 * Creates a new TspPluginContext instance.
 */
export function createPluginContext(options: CreatePluginContextOptions): TspPluginContext {
  return new TspPluginContextImpl(options)
}
