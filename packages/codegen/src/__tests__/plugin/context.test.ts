import { describe, expect, it } from 'vitest'
import type { OasDocument } from '@oa-sdk/parser'
import {
  createPluginContext,
  formatEsmImportExtension,
  normalizeVirtualPath,
  TspPluginContextImpl,
} from '../../plugin/context.js'
import {
  type TspConfig,
  type TspGeneratedFile,
  TspFileConflictError,
} from '../../plugin/types.js'

const mockDoc: OasDocument = {
  openapi: '3.2.0',
  info: {
    title: 'Test API',
    version: '1.0.0',
  },
  paths: {
    '/users': {
      get: {
        operationId: 'listUsers',
        responses: {
          '200': {
            description: 'Success',
          },
        },
      },
    },
  },
} as any

const mockConfig: TspConfig = {
  input: 'main.tsp',
  outputDir: './dist',
  plugins: [],
}

describe('TspPluginContext & Virtual File System', () => {
  it('initializes context with provided parameters and exposes them', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
      openApiVersion: '3.2.0',
    })

    expect(ctx.entrypoint).toBe('/app/main.tsp')
    expect(ctx.outputDir).toBe('/app/dist')
    expect(ctx.document).toBe(mockDoc)
    expect(ctx.openApiVersion).toBe('3.2.0')
    expect(ctx.getFiles()).toEqual([])
    expect(ctx.diagnostics).toEqual([])
  })

  it('normalizes virtual file paths and sets default generated banner', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
    })

    ctx.addFile({
      path: './src/models/types.ts',
      content: 'export interface User {}',
      sourcePlugin: 'typescript',
    })

    const file = ctx.getFile('src/models/types.ts')
    expect(file).toBeDefined()
    expect(file?.path).toBe('src/models/types.ts')
    expect(file?.banner).toBe('// @generated by @oa-sdk/codegen. DO NOT EDIT.')
    expect(ctx.hasFile('src/models/types.ts')).toBe(true)
    expect(ctx.hasFile('./src/models/types.ts')).toBe(true)
  })

  it('preserves custom banner if explicitly provided', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
    })

    ctx.addFile({
      path: 'banner-test.ts',
      content: '// test',
      sourcePlugin: 'custom',
      banner: '/* Custom Banner */',
    })

    expect(ctx.getFile('banner-test.ts')?.banner).toBe('/* Custom Banner */')
  })

  it('throws TspFileConflictError when two different plugins write to the same path', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
    })

    ctx.addFile({
      path: 'index.ts',
      content: '// from ts',
      sourcePlugin: 'typescript',
    })

    expect(() => {
      ctx.addFile({
        path: 'index.ts',
        content: '// from client',
        sourcePlugin: 'client',
      })
    }).toThrow(TspFileConflictError)

    try {
      ctx.addFile({
        path: 'index.ts',
        content: '// from client',
        sourcePlugin: 'client',
      })
    } catch (e) {
      const err = e as TspFileConflictError
      expect(err.filePath).toBe('index.ts')
      expect(err.existingPlugin).toBe('typescript')
      expect(err.conflictingPlugin).toBe('client')
      expect(err.message).toContain('already registered by "typescript"')
    }
  })

  it('allows same plugin to overwrite or update an existing file', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
    })

    ctx.addFile({
      path: 'types.ts',
      content: 'export type A = 1',
      sourcePlugin: 'typescript',
    })

    ctx.addFile({
      path: 'types.ts',
      content: 'export type A = 2',
      sourcePlugin: 'typescript',
    })

    expect(ctx.getFile('types.ts')?.content).toBe('export type A = 2')
  })

  it('updates file in place via updateFile', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
    })

    ctx.addFile({
      path: 'client.ts',
      content: 'export const a = 1',
      sourcePlugin: 'client',
    })

    ctx.updateFile('client.ts', existing => ({
      ...existing,
      content: existing.content + '\nexport const b = 2',
    }))

    expect(ctx.getFile('client.ts')?.content).toContain('export const b = 2')
  })

  it('throws when updating a non-existent file', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
    })

    expect(() => {
      ctx.updateFile('missing.ts', f => f)
    }).toThrow(/does not exist in context/)
  })

  it('removes a registered virtual file', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
    })

    ctx.addFile({
      path: 'temp.ts',
      content: '// temp',
      sourcePlugin: 'test',
    })

    expect(ctx.removeFile('temp.ts')).toBe(true)
    expect(ctx.hasFile('temp.ts')).toBe(false)
    expect(ctx.removeFile('temp.ts')).toBe(false)
  })

  describe('resolveImport', () => {
    const ctx = createPluginContext({
      entrypoint: '/app/main.tsp',
      outputDir: '/app/dist',
      document: mockDoc,
      config: mockConfig,
    })

    it('resolves sibling files in the root folder with ./ and .js extension', () => {
      expect(ctx.resolveImport('client.ts', 'types.ts')).toBe('./types.js')
      expect(ctx.resolveImport('./client.ts', './types.ts')).toBe('./types.js')
    })

    it('resolves child to parent directory with ../', () => {
      expect(ctx.resolveImport('sub/client.ts', 'types.ts')).toBe('../types.js')
      expect(ctx.resolveImport('a/b/client.ts', 'a/types.ts')).toBe('../types.js')
      expect(ctx.resolveImport('a/b/client.ts', 'types.ts')).toBe('../../types.js')
    })

    it('resolves parent to child directory with ./path/', () => {
      expect(ctx.resolveImport('client.ts', 'sub/types.ts')).toBe('./sub/types.js')
    })

    it('resolves sibling directories with ../sibling/', () => {
      expect(ctx.resolveImport('features/users/client.ts', 'features/auth/types.ts')).toBe(
        '../auth/types.js',
      )
    })

    it('throws when attempting to resolve a self-import', () => {
      expect(() => ctx.resolveImport('types.ts', 'types.ts')).toThrow(
        /Self-import is not allowed/,
      )
    })
  })

  describe('Shared Data Bus', () => {
    it('stores and retrieves arbitrary typed plugin shared state', () => {
      const ctx = createPluginContext({
        entrypoint: '/app/main.tsp',
        outputDir: '/app/dist',
        document: mockDoc,
        config: mockConfig,
      })

      ctx.setPluginData('ts-symbols', ['User', 'Pet', 'Order'])
      expect(ctx.getPluginData<string[]>('ts-symbols')).toEqual(['User', 'Pet', 'Order'])
      expect(ctx.getPluginData('non-existent')).toBeUndefined()
    })
  })

  describe('Diagnostics & Logging', () => {
    it('records diagnostics and logs warnings/errors', () => {
      const ctx = createPluginContext({
        entrypoint: '/app/main.tsp',
        outputDir: '/app/dist',
        document: mockDoc,
        config: mockConfig,
      })

      ctx.reportDiagnostic({
        message: 'Something looks odd',
        severity: 'info',
      })

      ctx.log('warn', 'Deprecated decorator used')
      ctx.log('error', 'Critical failure in transformation')

      expect(ctx.diagnostics).toHaveLength(3)
      expect(ctx.diagnostics[0]?.severity).toBe('info')
      expect(ctx.diagnostics[1]?.severity).toBe('warning')
      expect(ctx.diagnostics[2]?.severity).toBe('error')
    })
  })

  describe('ParsedDocument lazy initialization', () => {
    it('lazily parses OasDocument into ParsedDocument and caches the result', () => {
      const ctx = createPluginContext({
        entrypoint: '/app/main.tsp',
        outputDir: '/app/dist',
        document: mockDoc,
        config: mockConfig,
      })

      const parsed1 = ctx.parsed
      expect(parsed1).toBeDefined()
      expect(parsed1.operations).toBeDefined()
      expect(parsed1.operations.length).toBeGreaterThan(0)
      expect(parsed1.operations[0]?.operationId).toBe('listUsers')

      // Subsequent access returns cached instance
      const parsed2 = ctx.parsed
      expect(parsed2).toBe(parsed1)
    })
  })
})
