import { describe, expect, it } from 'vitest'
import { parse } from 'yaml'
import { createPluginContext } from '../plugin/context.js'
import { pydantic } from '../plugin/plugins/pydantic.js'

describe('pydantic plugin', () => {
  it('adds the Python module, IR, banner, and diagnostics', async () => {
    const context = createPluginContext({
      entrypoint: '/tmp/main.tsp', outputDir: '/tmp/out',
      document: parse('openapi: 3.2.0\ninfo: {title: test, version: "1"}\ncomponents: {schemas: {M: {type: object}}}\n'),
      config: { input: '/tmp/main.tsp' },
    })
    await pydantic({ emitIr: true }).generate!(context, undefined)
    expect(context.getFile('models.py')?.banner).toContain('# @generated by @oa-sdk/codegen')
    expect(context.getFile('models.py.ir.json')).toBeDefined()
    expect(context.diagnostics.every(diagnostic => diagnostic.plugin === 'pydantic')).toBe(true)
  })
})
