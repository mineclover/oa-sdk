from collections.abc import Mapping
from typing import Any, Protocol, runtime_checkable

OpenApiDocument = Mapping[str, Any]


@runtime_checkable
class RuntimeOpenApiAdapter(Protocol):
    """Framework adapter interface for extracting runtime OpenAPI documents."""

    @property
    def name(self) -> str:
        """Stable machine-readable adapter name."""
        ...

    @property
    def framework(self) -> str:
        """Human-readable framework name for reports."""
        ...

    def extract_openapi(self, runtime: object) -> OpenApiDocument:
        """Return the OpenAPI document generated by a framework runtime object."""
        ...
